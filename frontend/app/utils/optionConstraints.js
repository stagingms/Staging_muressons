/**
 * Resolve the constraint for an option.
 *
 * The positional fallback is not defensive padding: detailedDescriptions keys
 * pillar copy positionally (option_1, option_2, …) while the engine's keys are
 * semantic (renewable_ppa, …). A direct lookup missed 150 of 150 options once
 * already — see __tests__/pillar-option-descriptions.test.js. Same shape here,
 * same fallback.
 */
export function optionConstraint({ paradigm, roundNumber, optionKey, areaKey = null, index = null }) {
  const round = OPTION_CONSTRAINTS?.[paradigm]?.[String(roundNumber)];
  if (!round) return '';
  const bucket = areaKey ? round[areaKey] : round;
  if (!bucket) return '';
  if (bucket[optionKey]) return bucket[optionKey];
  if (index != null && bucket[`option_${index + 1}`]) return bucket[`option_${index + 1}`];
  return '';
}

/**
 * Split an authored constraint into renderable segments.
 *
 * The alternative was dangerouslySetInnerHTML, and that is the wrong trade for
 * content a facilitator edits: it makes a copy file into a script-injection
 * surface, and the only markup this needs is emphasis. Segments in, React
 * nodes out, no HTML parsed anywhere.
 *
 * Returns [{ bold: boolean, text: string }]. Anything that is not <b> or </b>
 * is treated as literal text and rendered as such — a stray tag shows up as a
 * stray tag, which is exactly the feedback an author wants.
 */
export function constraintSegments(text) {
  if (!text) return [];
  const out = [];
  const re = /<b>([\s\S]*?)<\/b>/g;
  let last = 0, m;
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) out.push({ bold: false, text: text.slice(last, m.index) });
    out.push({ bold: true, text: m[1] });
    last = re.lastIndex;
  }
  if (last < text.length) out.push({ bold: false, text: text.slice(last) });
  return out.filter((s) => s.text !== '');
}

